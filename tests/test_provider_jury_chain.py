    def test_confirmed_context_pins_both_runtimes_and_registry_policy(self) -> None:
        settlement_code, registry_code = b"settlement-runtime", b"registry-runtime"
        config = replace(
            self.config,
            settlement_runtime_code_hash="0x" + chain.keccak256(settlement_code).hex(),
            registry_runtime_code_hash="0x" + chain.keccak256(registry_code).hex(),
        )
        now = int(time.time())
        uint_values = {
            "adjudicationThreshold()": 2, "PROTOCOL_VERSION()": 10,
            "minimumReputation()": 80, "jurySize()": 3, "threshold()": 2,
            "selectionDelayBlocks()": 2,
        }
        address_values = {
            "juryRegistry()": self.registry, "settlement()": self.contract,
            "governance()": self.governance,
            "reputationAuthority()": self.reputation_authority,
            "bondPenaltyRecipient()": self.penalty,
        }
        selectors = {
            chain.encode_contract_call(signature, [])[:10]: ("uint", value)
            for signature, value in uint_values.items()
        }
        selectors.update({
            chain.encode_contract_call(signature, [])[:10]: ("address", value)
            for signature, value in address_values.items()
        })
        selectors[chain.encode_contract_call("RANDOMNESS_MODE_HASH()", [])[:10]] = (
            "hash", "0x" + chain.keccak256(b"future_blockhash_v1").hex(),
        )

        def rpc(method, params):
            if method == "eth_chainId":
                return hex(31337)
            if method == "eth_blockNumber":
                return "0x65"
            if method == "eth_getBlockByNumber" and params[0] == "0x0":
                return {"hash": digest(100)}
            if method == "eth_getBlockByNumber" and params[0] == "0x64":
                return {"number": "0x64", "hash": digest(200), "timestamp": hex(now)}
            if method == "eth_getCode":
                return "0x" + (settlement_code if params[0] == self.contract else registry_code).hex()
            if method == "eth_call":
                kind, value = selectors[params[0]["data"][:10]]
                if kind == "uint":
                    return "0x" + _word_uint(value).hex()
                if kind == "address":
                    return "0x" + _word_address(value).hex()
                return value
            self.fail(f"unexpected RPC {method} {params}")

        adapter = ProviderJuryChainAdapter(
            config, outbox_path=Path(self.temporary.name) / "context.sqlite3",
            resolve_provider=lambda _snapshot: {}, sender=self.sender, rpc=rpc,
            allow_test_rpc_override=True,
        )
        self.addCleanup(adapter.close)
        context = adapter.confirmed_context()
        self.assertEqual(context["block_number"], 100)
        self.assertEqual(context["block_hash"], digest(200))

        uint_values["threshold()"] = 3
        selectors[chain.encode_contract_call("threshold()", [])[:10]] = ("uint", 3)
        with self.assertRaisesRegex(ProviderJuryChainError, "differs from"):
            adapter.confirmed_context()

