    def test_retry_events_are_bound_to_case_roster_and_receipt(self) -> None:
        adapter = self.adapter(name="retry-events.sqlite3")
        self.addCleanup(adapter.close)
        case_id, tx_hash, block_hash = digest(7), digest(30), digest(31)
        receipt = {
            "transaction_hash": tx_hash, "block_hash": block_hash,
            "block_number": 100,
        }
        action = {
            "settlement_key": case_id, "registry_roster_version": 10,
        }
        common = {
            "address": self.registry, "transactionHash": tx_hash,
            "blockHash": block_hash, "blockNumber": "0x64",
            "logIndex": "0x0", "removed": False,
        }
        requested = {
            **common,
            "topics": [JURY_REQUESTED_TOPIC, case_id, digest(10)],
            "data": "0x" + (_word_uint(125) + _word_hash(digest(40))).hex(),
        }
        event = adapter._retry_event([requested], receipt=receipt, action=action)
        self.assertEqual(event["event"], "JuryRequested")
        self.assertEqual(event["selection_block"], 125)
        # Roster updates can land after the hash-pinned preflight but before
        # mining; monotonic advancement is safe and the refreshed assignment
        # is checked separately.
        advanced = adapter._retry_event(
            [requested], receipt=receipt,
            action={**action, "registry_roster_version": 9},
        )
        self.assertEqual(advanced["roster_version"], 10)

        unavailable = {
            **common,
            "topics": [JURY_UNAVAILABLE_TOPIC, case_id, digest(10)],
            "data": "0x" + _word_uint(2).hex(),
        }
        event = adapter._retry_event([unavailable], receipt=receipt, action=action)
        self.assertEqual(event["event"], "JuryUnavailable")
        self.assertEqual(event["independent_candidate_count"], 2)
        with self.assertRaisesRegex(ProviderJuryChainError, "regressed"):
            adapter._retry_event(
                [unavailable], receipt=receipt,
                action={**action, "registry_roster_version": 11},
            )
        with self.assertRaisesRegex(ProviderJuryChainError, "one retry outcome"):
            adapter._retry_event(
                [requested, unavailable], receipt=receipt, action=action,
            )


