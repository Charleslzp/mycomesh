    def test_assignment_info_decoder_rejects_noncanonical_dynamic_offsets(self) -> None:
        adapter = self.adapter()
        self.addCleanup(adapter.close)
        owners = [address(1), address(2), address(3)]
        signers = [address(11), address(12), address(13)]
        operators = [digest(21), digest(22), digest(23)]
        arrays = [
            _word_uint(len(owners)) + b"".join(_word_address(item) for item in owners),
            _word_uint(len(signers)) + b"".join(_word_address(item) for item in signers),
            _word_uint(len(operators)) + b"".join(_word_hash(item) for item in operators),
        ]
        offsets, cursor = [], 8 * 32
        for item in arrays:
            offsets.append(cursor)
            cursor += len(item)
        head = b"".join((
            _word_uint(2), _word_uint(100), _word_uint(9), _word_hash(digest(8)),
            _word_hash(digest(9)), *(_word_uint(item) for item in offsets),
        ))
        encoded = head + b"".join(arrays)
        adapter._call = lambda *_args, **_kwargs: encoded
        decoded = adapter._assignment_info(digest(7), "latest")
        self.assertEqual(decoded["owners"], owners)
        self.assertEqual(decoded["vote_signers"], signers)

        malformed = bytearray(encoded)
        malformed[6 * 32:7 * 32] = _word_uint(offsets[1] + 32)
        adapter._call = lambda *_args, **_kwargs: bytes(malformed)
        with self.assertRaisesRegex(ProviderJuryChainError, "noncanonical array offsets"):
            adapter._assignment_info(digest(7), "latest")

    def test_outbox_crash_recovery_never_reuses_or_blindly_resends_nonce(self) -> None:
        path = Path(self.temporary.name) / "outbox.sqlite3"
        action = self.action_fixture()
        outbox = JuryTransactionOutbox(path)
        saved = outbox.reserve(
            action=action, scope=f"{digest(100)}:31337", sender=self.sender,
            nonce=7, target=self.contract, calldata="0x1234",
            gas_price_wei=1, gas_units=100_000,
            raw_tx=self.signed_raw(action, nonce=7),
        )
        outbox.begin_send(action["action_hash"])
        outbox.close()

        recovered = JuryTransactionOutbox(path)
        self.addCleanup(recovered.close)
        self.assertEqual(recovered.get(action["action_hash"])["state"], "uncertain")
        storage = recovered.storage_health()
        self.assertTrue(storage["ready"])
        self.assertEqual(storage["backlog_count"], 1)
        self.assertEqual(storage["uncertain_count"], 1)
        next_action = self.action_fixture(calldata="0x5678")
        with self.assertRaisesRegex(ProviderJuryChainError, "unresolved"):
            recovered.reserve(
                action=next_action,
                scope=f"{digest(100)}:31337", sender=self.sender, nonce=8,
                target=self.contract, calldata="0x5678", gas_price_wei=1,
                gas_units=100_000,
                raw_tx=self.signed_raw(next_action, nonce=8),
            )
        self.assertEqual(recovered.get(action["action_hash"])["tx_hash"], saved["tx_hash"])

