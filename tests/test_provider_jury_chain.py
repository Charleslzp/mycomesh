    def test_outbox_rejects_unsafe_paths_and_detects_open_time_swap(self) -> None:
        original = Path(self.temporary.name) / "linked.sqlite3"
        original.touch(mode=0o600)
        alias = Path(self.temporary.name) / "linked-alias.sqlite3"
        os.link(original, alias)
